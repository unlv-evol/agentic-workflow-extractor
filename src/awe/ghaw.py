"""GitHub Agentic Workflows (`gh-aw`) artifacts.

`gh-aw` is GitHub's first-party agentic workflow framework: an agent is
authored as Markdown in `.github/workflows/` and compiled by `gh aw compile`
into an ordinary `.github/workflows/<name>.lock.yml`. Both halves are checked
in, so both are visible in git history.

This is a different detection problem from the rest of `awe`. Elsewhere we
infer that a step invokes an agent by pattern-matching a catalogue against
free-form YAML. Here the compiler stamps a machine-readable manifest into the
head of every file it generates, so detection is exact and the payload is far
richer: which agent and which version, the tools it may call, the outputs it is
permitted to emit, its network egress policy, and its sandbox.

Two artifact kinds are recognised:

``lock``
    A compiled `*.lock.yml`, carrying ``# gh-aw-metadata:`` and
    ``# gh-aw-manifest:`` JSON header lines.
``source``
    The authored Markdown, carrying YAML frontmatter with ``engine``,
    ``tools``, ``safe-outputs`` and friends.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field

import yaml

# Emitted verbatim by the compiler into every generated file.
GENERATED_MARKER = "automatically generated by gh-aw"
_METADATA_PREFIX = "# gh-aw-metadata:"
_MANIFEST_PREFIX = "# gh-aw-manifest:"

# The header layout has changed across compiler releases, so the scan reads
# the leading comment block rather than a fixed number of lines. In v0.56.2
# (schema v2) an ASCII-art banner comes first, the marker lands on line 16 and
# the metadata on line 26; by schema v4 the metadata and manifest are the first
# two lines. A fixed 12-line window found the newer layout and silently missed
# every older one -- 17 of 17 lock files in one adopter repository.
_HEADER_SCAN_LINES = 200

# `gh-aw (v0.56.2)` in the generated-by marker.
_COMPILER_VERSION_RE = re.compile(r"gh-aw\s*\(v?([0-9][\w.+-]*)\)")

# Frontmatter keys carried through to the manifest table. Chosen because each
# expresses a constraint a maintainer placed on the agent, which is the point
# of the table -- not merely that an agent is present, but how much rope it
# was given.
_GOVERNANCE_KEYS = (
    "on",
    "engine",
    "model",
    "tools",
    "safe-outputs",
    "sandbox",
    "network",
    "permissions",
    "imports",
    "evals",
    "strict",
    "timeout-minutes",
    "max-turns",
    "features",
)


@dataclass
class GhawFacts:
    """One revision of one gh-aw artifact."""

    kind: str  # "lock" | "source"
    agent_id: str | None = None
    engine_version: str | None = None
    schema_version: str | None = None
    compiler_version: str | None = None
    strict: bool | None = None
    model: str | None = None
    tools: tuple[str, ...] = ()
    mcp_tools: tuple[str, ...] = ()
    safe_outputs: tuple[str, ...] = ()
    secrets: tuple[str, ...] = ()
    actions: tuple[str, ...] = ()
    containers: tuple[str, ...] = ()
    imports: tuple[str, ...] = ()
    sandboxed: bool | None = None
    network: str | None = None
    permissions: str | None = None
    n_evals: int = 0
    timeout_minutes: int | None = None
    max_turns: int | None = None
    frontmatter_keys: tuple[str, ...] = ()
    parse_ok: bool = True
    extra: dict = field(default_factory=dict)


def _json_after(line: str, prefix: str) -> dict | None:
    try:
        return json.loads(line[len(prefix) :].strip())
    except (ValueError, TypeError):
        return None


def _flatten(value) -> tuple[str, ...]:
    """Keys of a mapping, items of a sequence, or the value itself."""
    if value is None or value is False:
        return ()
    if value is True:
        return ("true",)
    if isinstance(value, dict):
        return tuple(str(k) for k in value)
    if isinstance(value, (list, tuple)):
        out: list[str] = []
        for item in value:
            if isinstance(item, dict):
                # `imports` entries are either a bare path or {uses: path, ...}
                out.append(str(item.get("uses") or next(iter(item), "")))
            else:
                out.append(str(item))
        return tuple(out)
    return (str(value),)


def is_lock_file(file_path: str) -> bool:
    return file_path.endswith((".lock.yml", ".lock.yaml"))


def is_workflow_markdown(file_path: str) -> bool:
    return file_path.endswith(".md") and ".github/workflows/" in f"/{file_path}"


def _parse_lock(content: str) -> GhawFacts | None:
    metadata: dict = {}
    manifest: dict = {}
    seen_marker = False
    compiler_version: str | None = None

    for line in content.splitlines()[:_HEADER_SCAN_LINES]:
        if not line.startswith("#"):
            # The generated header is one contiguous comment block; once real
            # YAML starts there is nothing left to find.
            break
        if line.startswith(_METADATA_PREFIX):
            metadata = _json_after(line, _METADATA_PREFIX) or {}
        elif line.startswith(_MANIFEST_PREFIX):
            manifest = _json_after(line, _MANIFEST_PREFIX) or {}
        elif GENERATED_MARKER in line:
            seen_marker = True
            found = _COMPILER_VERSION_RE.search(line)
            if found:
                compiler_version = found.group(1)

    if not (metadata or manifest or seen_marker):
        return None

    # Schema v2 names the compiler in the metadata; v4 only in the marker. The
    # two spell it differently ("v0.56.2" against "0.56.2"), so normalise.
    compiler_version = metadata.get("compiler_version") or compiler_version
    if isinstance(compiler_version, str):
        compiler_version = compiler_version.lstrip("vV") or None

    engines = metadata.get("engine_versions")
    agent_id = metadata.get("agent_id")
    engine_version = None
    if isinstance(engines, dict) and engines:
        engine_version = str(
            engines.get(agent_id) if agent_id in engines else next(iter(engines.values()))
        )

    mcp_tools: list[str] = []
    servers = manifest.get("mcp_servers")
    if isinstance(servers, list):
        for server in servers:
            if not isinstance(server, dict):
                continue
            name = server.get("name", "?")
            for tool in server.get("tools") or ():
                mcp_tools.append(f"{name}:{tool}")

    def _repos(key: str, field_name: str) -> tuple[str, ...]:
        items = manifest.get(key)
        if not isinstance(items, list):
            return ()
        return tuple(
            str(i.get(field_name)) for i in items if isinstance(i, dict) and i.get(field_name)
        )

    return GhawFacts(
        kind="lock",
        agent_id=str(agent_id) if agent_id else None,
        engine_version=engine_version,
        schema_version=(
            str(metadata.get("schema_version")) if metadata.get("schema_version") else None
        ),
        strict=metadata.get("strict") if isinstance(metadata.get("strict"), bool) else None,
        compiler_version=str(compiler_version) if compiler_version else None,
        mcp_tools=tuple(mcp_tools),
        secrets=_flatten(manifest.get("secrets")),
        actions=_repos("actions", "repo"),
        containers=_repos("containers", "image"),
        parse_ok=bool(metadata or manifest or seen_marker),
    )


def _parse_source(content: str) -> GhawFacts | None:
    if not content.startswith("---"):
        return None
    parts = content.split("---", 2)
    if len(parts) < 3:
        return None
    try:
        front = yaml.safe_load(parts[1])
    except (yaml.YAMLError, RecursionError, ValueError):
        return GhawFacts(kind="source", parse_ok=False)
    if not isinstance(front, dict):
        return None

    # `on:` is the YAML 1.1 boolean True unless quoted, exactly as in a
    # workflow file, so the trigger arrives under a key of `True`.
    if "on" not in front and True in front:
        front["on"] = front[True]

    # An agentic workflow source is distinguished from any other Markdown file
    # with frontmatter by declaring at least one of the framework's own keys.
    if not any(key in front for key in ("engine", "tools", "safe-outputs", "imports")):
        return None

    engine = front.get("engine")
    if isinstance(engine, dict):
        agent_id = engine.get("id")
        engine_version = engine.get("version")
    else:
        agent_id = engine
        engine_version = None

    network = front.get("network")
    return GhawFacts(
        kind="source",
        agent_id=str(agent_id) if agent_id else None,
        engine_version=str(engine_version) if engine_version else None,
        strict=front.get("strict") if isinstance(front.get("strict"), bool) else None,
        model=str(front.get("model")) if front.get("model") else None,
        tools=_flatten(front.get("tools")),
        safe_outputs=_flatten(front.get("safe-outputs")),
        imports=_flatten(front.get("imports")),
        sandboxed=front.get("sandbox") is not None,
        network=(
            "custom" if isinstance(network, dict) else (str(network) if network else None)
        ),
        permissions=" ".join(_flatten(front.get("permissions"))) or None,
        n_evals=len(_flatten(front.get("evals"))),
        timeout_minutes=(
            front.get("timeout-minutes")
            if isinstance(front.get("timeout-minutes"), int)
            else None
        ),
        max_turns=front.get("max-turns") if isinstance(front.get("max-turns"), int) else None,
        frontmatter_keys=tuple(str(k) for k in front),
        extra={k: front[k] for k in _GOVERNANCE_KEYS if k in front},
    )


def analyse(file_path: str, content: str) -> GhawFacts | None:
    """Recognise a gh-aw artifact, or return None if this is not one."""
    if is_lock_file(file_path):
        return _parse_lock(content)
    if is_workflow_markdown(file_path):
        return _parse_source(content)
    # A compiled workflow that was renamed away from `.lock.yml` still carries
    # the compiler's marker.
    if GENERATED_MARKER in content[:2000]:
        return _parse_lock(content)
    return None
